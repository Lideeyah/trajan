// Generated-file templates. One `trajan.ts` module per framework; the seller imports
// `paid` and `mountTrajan` from it and leaves their own routes untouched.

export type Framework = 'hono' | 'express' | 'mcp'
export type Network = 'moderato' | 'mainnet'

export type Config = {
  framework: Framework
  network: Network
  recipient: `0x${string}`
  currency: `0x${string}`
  price: string
  db: string
  /** Port for the console when the host app has no HTTP server of its own (MCP over stdio). */
  apiPort: number
  name: string
}

const header = (c: Config) => `// Generated by \`trajan init\`. Safe to edit.
// Network: Tempo ${c.network === 'moderato' ? 'Moderato testnet' : 'mainnet'} · recipient ${c.recipient} · ${c.price} per call
`

const net = (c: Config) => (c.network === 'moderato'
  ? { rpc: 'MODERATO_RPC', tx: 'MODERATO_EXPLORER_TX', addr: 'MODERATO_EXPLORER_ADDRESS', testnet: 'true' }
  : { rpc: 'MAINNET_RPC', tx: 'MAINNET_EXPLORER_TX', addr: 'MAINNET_EXPLORER_ADDRESS', testnet: 'false' })

const common = (c: Config) => {
  const n = net(c)
  return `
import { createCallLog, attachCallLog, createWallet, trajanConsole, ${n.rpc}, ${n.tx}, ${n.addr} } from '@trajan/server'

const config = JSON.parse(readFileSync(new URL('./trajan.config.json', import.meta.url), 'utf8')) as {
  name: string; recipient: \`0x\${string}\`; currency: \`0x\${string}\`; price: string; db: string; apiPort: number
}

if (!process.env.MPP_SECRET_KEY) throw new Error('MPP_SECRET_KEY is not set (see .env)')

/** Optional: sponsor buyers' fees. Set TRAJAN_FEE_PAYER_KEY to a funded account (fees are paid in the stablecoin). */
const feePayer = process.env.TRAJAN_FEE_PAYER_KEY ? privateKeyToAccount(process.env.TRAJAN_FEE_PAYER_KEY as \`0x\${string}\`) : undefined
`
}

const snippetFor = (c: Config) => c.framework === 'mcp'
  ? "registerPaidTool(server, 'name', { description, inputSchema }, handler)\nstartTrajanApi()"
  : "app.get('/your-route', paid(), handler)\nmountTrajan(app)"

const tail = (c: Config) => {
  const n = net(c)
  return `
/** One row per paid call, written from mppx's payment hook. Handlers are never wrapped. */
export const log = createCallLog(config.db)
attachCallLog(mppx, log, {
  rpcUrl: ${n.rpc},
  // Trajan Cloud: set TRAJAN_CLOUD_URL + TRAJAN_API_KEY (written by \`trajan init --cloud\`) to see calls in your hosted console.
  cloud: process.env.TRAJAN_API_KEY ? { url: (process.env.TRAJAN_CLOUD_URL ?? 'https://trajan.vercel.app') + '/ingest', apiKey: process.env.TRAJAN_API_KEY } : undefined,
})

/** Balance always; withdraw only when TRAJAN_WITHDRAW_KEY (the recipient's key) is set. */
export const wallet = createWallet({
  recipient: config.recipient,
  token: config.currency,
  testnet: ${n.testnet},
  withdrawKey: process.env.TRAJAN_WITHDRAW_KEY as \`0x\${string}\` | undefined,
})

/** The console: page at /, JSON under /api. */
export const console_ = trajanConsole(log, {
  name: config.name,
  network: '${c.network}',
  wallet,
  price: config.price,
  snippet: ${JSON.stringify(snippetFor(c))},
  explorerTxBase: ${n.tx},
  explorerAddressBase: ${n.addr},
})
`
}

const chargeMethod = (c: Config) =>
  `tempo.charge({ currencies: [config.currency], recipient: config.recipient${c.network === 'moderato' ? ', testnet: true' : ''}, feePayer })`

export function honoTemplate(c: Config) {
  return `${header(c)}import { readFileSync } from 'node:fs'
import type { Hono } from 'hono'
import { Mppx, tempo } from 'mppx/hono'
import { privateKeyToAccount } from 'viem/accounts'${common(c)}
export const mppx = Mppx.create({
  methods: [${chargeMethod(c)}],
  secretKey: process.env.MPP_SECRET_KEY,
})
${tail(c)}
/** Gate a route: \`app.get('/tool', paid(), handler)\`. Override the price per route with \`paid('0.05')\`. */
export const paid = (amount: string = config.price) => mppx.charge({ amount })

/** Mount the console at /trajan (page) and /trajan/api/* (JSON). */
export function mountTrajan(app: Hono) {
  app.route('/trajan', console_)
}
`
}

export function expressTemplate(c: Config) {
  return `${header(c)}import { readFileSync } from 'node:fs'
import type { Express } from 'express'
import { Hono } from 'hono'
import { Mppx, tempo } from 'mppx/express'
import { privateKeyToAccount } from 'viem/accounts'${common(c)}
export const mppx = Mppx.create({
  methods: [${chargeMethod(c)}],
  secretKey: process.env.MPP_SECRET_KEY,
})
${tail(c)}
/** Gate a route: \`app.get('/tool', paid(), handler)\`. Override the price per route with \`paid('0.05')\`. */
export const paid = (amount: string = config.price) => mppx.charge({ amount })

/** Mount the console at /trajan (served by a small embedded Hono app). */
export function mountTrajan(app: Express) {
  const hono = new Hono().route('/trajan', console_)
  app.use('/trajan', async (req, res) => {
    const url = new URL(req.originalUrl, \`http://\${req.headers.host ?? 'localhost'}\`)
    const init: RequestInit = { method: req.method, headers: req.headers as Record<string, string> }
    if (req.method !== 'GET' && req.method !== 'HEAD') {
      const chunks: Buffer[] = []
      for await (const ch of req) chunks.push(ch as Buffer)
      init.body = Buffer.concat(chunks)
    }
    const r = await hono.fetch(new Request(url, init))
    res.status(r.status)
    r.headers.forEach((v, k) => res.setHeader(k, v))
    res.send(Buffer.from(await r.arrayBuffer()))
  })
}
`
}

export function mcpTemplate(c: Config) {
  return `${header(c)}import { readFileSync } from 'node:fs'
import { Hono } from 'hono'
import { serve } from '@hono/node-server'
import { Mppx, Transport, tempo } from 'mppx/server'
import { privateKeyToAccount } from 'viem/accounts'
import type { CallToolResult } from '@modelcontextprotocol/sdk/types.js'${common(c)}
export const mppx = Mppx.create({
  methods: [${chargeMethod(c)}],
  secretKey: process.env.MPP_SECRET_KEY,
  realm: config.name,
  transport: Transport.mcpSdk(),
})
${tail(c)}
type ToolHandler<A, R> = (args: A, extra: any) => Promise<R>
type PaidOptions = { amount?: string; name?: string }

/**
 * Wrap an MCP tool handler so it requires payment. Pass the tool name so the console
 * can show it (MCP calls have no HTTP path):
 *   server.registerTool('search', { ... }, paid(async (args) => ({ content: [...] }), { name: 'search' }))
 * An unpaid call returns the MPP challenge; a paid call runs the handler and attaches the receipt.
 */
export function paid<A, R extends CallToolResult>(handler: ToolHandler<A, R>, opts: PaidOptions | string = {}) {
  const { amount = config.price, name } = typeof opts === 'string' ? { amount: opts } : opts
  return async (args: A, extra: any) => {
    const result = await mppx.charge({ amount, description: name })(extra)
    if (result.status === 402) throw result.challenge
    const out = await handler(args, extra)
    // Tell the buyer what this call cost: the MPP receipt carries a tx reference but no amount.
    const meta = { ...(out._meta ?? {}), 'trajan/charge': { amount, currency: config.currency, tool: name ?? null } }
    return result.withReceipt({ ...out, _meta: meta })
  }
}

/** registerTool + paid in one call, so the tool name is only written once. */
export function registerPaidTool<A, R extends CallToolResult>(
  server: { registerTool: (name: string, cfg: any, cb: any) => unknown },
  name: string,
  cfg: Record<string, unknown>,
  handler: ToolHandler<A, R>,
  amount: string = config.price,
) {
  return server.registerTool(name, cfg, paid(handler, { amount, name }))
}

/** The MCP server has no HTTP surface of its own, so serve the console on its own port. */
export function startTrajanApi(port: number = Number(process.env.TRAJAN_CONSOLE_PORT ?? config.apiPort)) {
  const app = new Hono().route('/trajan', console_)
  return serve({ fetch: app.fetch, port }, () => console.error(\`trajan console on http://localhost:\${port}/trajan\`))
}
`
}

export function template(c: Config) {
  return { hono: honoTemplate, express: expressTemplate, mcp: mcpTemplate }[c.framework](c)
}

export function nextSteps(c: Config, file: string) {
  const lines: Record<Framework, string[]> = {
    hono: [
      `import { paid, mountTrajan } from './${file}'`,
      `app.get('/your-route', paid(), handler)   // charge ${c.price} per call`,
      `mountTrajan(app)                          // console at /trajan`,
    ],
    express: [
      `import { paid, mountTrajan } from './${file}'`,
      `app.get('/your-route', paid(), handler)   // charge ${c.price} per call`,
      `mountTrajan(app)                          // console at /trajan`,
    ],
    mcp: [
      `import { registerPaidTool, startTrajanApi } from './${file}'`,
      `registerPaidTool(server, 'name', { description, inputSchema }, async (args) => ({ content: [...] }))`,
      `startTrajanApi()                          // console on :${c.apiPort}/trajan`,
    ],
  }
  return lines[c.framework]
}
