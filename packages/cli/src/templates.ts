// Generated-file templates. One `trajan.ts` module per framework; the seller imports
// `paid` and `mountTrajan` from it and leaves their own routes untouched.

export type Framework = 'hono' | 'express' | 'mcp'
export type Network = 'moderato' | 'mainnet'

export type Config = {
  framework: Framework
  network: Network
  recipient: `0x${string}`
  currency: `0x${string}`
  price: string
  db: string
  /** Port for the console API when the host app has no HTTP server of its own (MCP over stdio). */
  apiPort: number
}

const header = (c: Config) => `// Generated by \`trajan init\`. Safe to edit.
// Network: Tempo ${c.network === 'moderato' ? 'Moderato testnet' : 'mainnet'} · recipient ${c.recipient} · ${c.price} per call
`

const common = (c: Config) => `
import { createCallLog, attachCallLog, consoleApi, ${c.network === 'moderato' ? 'MODERATO_RPC, MODERATO_EXPLORER_TX' : 'MAINNET_RPC, MAINNET_EXPLORER_TX'} } from '@trajan/server'

const config = JSON.parse(readFileSync(new URL('./trajan.config.json', import.meta.url), 'utf8')) as {
  recipient: \`0x\${string}\`; currency: \`0x\${string}\`; price: string; db: string; apiPort: number
}

if (!process.env.MPP_SECRET_KEY) throw new Error('MPP_SECRET_KEY is not set (see .env)')
`

const logBlock = (c: Config) => `
/** One row per paid call, written from mppx's payment hook. Handlers are never wrapped. */
export const log = createCallLog(config.db)
attachCallLog(mppx, log, { rpcUrl: ${c.network === 'moderato' ? 'MODERATO_RPC' : 'MAINNET_RPC'} })

/** Read-only JSON API for the Trajan console. */
export const trajanApi = consoleApi(log, { explorerTxBase: ${c.network === 'moderato' ? 'MODERATO_EXPLORER_TX' : 'MAINNET_EXPLORER_TX'} })
`

export function honoTemplate(c: Config) {
  return `${header(c)}import { readFileSync } from 'node:fs'
import type { Hono } from 'hono'
import { Mppx, tempo } from 'mppx/hono'${common(c)}
export const mppx = Mppx.create({
  methods: [tempo.charge({ currencies: [config.currency], recipient: config.recipient${c.network === 'moderato' ? ', testnet: true' : ''} })],
  secretKey: process.env.MPP_SECRET_KEY,
})
${logBlock(c)}
/** Gate a route: \`app.get('/tool', paid(), handler)\`. Override the price per route with \`paid('0.05')\`. */
export const paid = (amount: string = config.price) => mppx.charge({ amount })

/** Mount the console API at /trajan/api. */
export function mountTrajan(app: Hono) {
  app.route('/trajan/api', trajanApi)
}
`
}

export function expressTemplate(c: Config) {
  return `${header(c)}import { readFileSync } from 'node:fs'
import type { Express } from 'express'
import { Hono } from 'hono'
import { Mppx, tempo } from 'mppx/express'${common(c)}
export const mppx = Mppx.create({
  methods: [tempo.charge({ currencies: [config.currency], recipient: config.recipient${c.network === 'moderato' ? ', testnet: true' : ''} })],
  secretKey: process.env.MPP_SECRET_KEY,
})
${logBlock(c)}
/** Gate a route: \`app.get('/tool', paid(), handler)\`. Override the price per route with \`paid('0.05')\`. */
export const paid = (amount: string = config.price) => mppx.charge({ amount })

/** Mount the console API at /trajan/api (served by a small embedded Hono app). */
export function mountTrajan(app: Express) {
  const api = new Hono().route('/trajan/api', trajanApi)
  app.use('/trajan/api', async (req, res) => {
    const url = new URL(req.originalUrl, \`http://\${req.headers.host ?? 'localhost'}\`)
    const r = await api.fetch(new Request(url, { method: req.method }))
    res.status(r.status)
    r.headers.forEach((v, k) => res.setHeader(k, v))
    res.send(Buffer.from(await r.arrayBuffer()))
  })
}
`
}

export function mcpTemplate(c: Config) {
  return `${header(c)}import { readFileSync } from 'node:fs'
import { Hono } from 'hono'
import { serve } from '@hono/node-server'
import { Mppx, Transport, tempo } from 'mppx/server'${common(c)}
export const mppx = Mppx.create({
  methods: [tempo.charge({ currencies: [config.currency], recipient: config.recipient${c.network === 'moderato' ? ', testnet: true' : ''} })],
  secretKey: process.env.MPP_SECRET_KEY,
  transport: Transport.mcpSdk(),
})
${logBlock(c)}
type ToolHandler<A, R> = (args: A, extra: any) => Promise<R>

/**
 * Wrap an MCP tool handler so it requires payment:
 *   server.registerTool('search', { ... }, paid(async (args) => ({ content: [...] })))
 * An unpaid call returns the MPP challenge; a paid call runs the handler and attaches the receipt.
 */
export function paid<A, R extends { content: unknown[] }>(handler: ToolHandler<A, R>, amount: string = config.price) {
  return async (args: A, extra: any) => {
    const result = await mppx.charge({ amount })(extra)
    if (result.status === 402) throw result.challenge
    return result.withReceipt(await handler(args, extra))
  }
}

/** The MCP server has no HTTP surface of its own, so serve the console API on its own port. */
export function startTrajanApi(port: number = config.apiPort) {
  const app = new Hono().route('/trajan/api', trajanApi)
  return serve({ fetch: app.fetch, port }, () => console.error(\`trajan console api on http://localhost:\${port}/trajan/api\`))
}
`
}

export function template(c: Config) {
  return { hono: honoTemplate, express: expressTemplate, mcp: mcpTemplate }[c.framework](c)
}

export function nextSteps(c: Config, file: string) {
  const lines: Record<Framework, string[]> = {
    hono: [
      `import { paid, mountTrajan } from './${file}'`,
      `app.get('/your-route', paid(), handler)   // charge ${c.price} per call`,
      `mountTrajan(app)                          // console API at /trajan/api`,
    ],
    express: [
      `import { paid, mountTrajan } from './${file}'`,
      `app.get('/your-route', paid(), handler)   // charge ${c.price} per call`,
      `mountTrajan(app)                          // console API at /trajan/api`,
    ],
    mcp: [
      `import { paid, startTrajanApi } from './${file}'`,
      `server.registerTool('name', { ... }, paid(async (args) => ({ content: [...] })))`,
      `startTrajanApi()                          // console API on :${c.apiPort}`,
    ],
  }
  return lines[c.framework]
}
